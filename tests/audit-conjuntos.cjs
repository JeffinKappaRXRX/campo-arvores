'use strict';
const assert=require('node:assert/strict'),Geo=require('../docs/ciclo-conjuntos.js'),Audit=require('../tools/audit-conjuntos.cjs');
const feature={type:'Feature',properties:{codigo:'42',nome:'TESTE'},geometry:{type:'Polygon',coordinates:[[[-70,-10],[-69,-10],[-69,-9],[-70,-9],[-70,-10]]]}};
const names={'42':'TESTE'},index=Geo.spatial([feature],'codigo',names,{});
assert.deepEqual(Audit.decode({n:2,c:{id:{k:['a','b'],i:[1,0]},lat:[-9.5,null]}}),[{id:'b',lat:-9.5},{id:'a',lat:null}]);
assert.throws(()=>Audit.decode({n:1,c:{id:{k:['a'],i:[3]}}}),/dictionary/);
assert.throws(()=>Audit.decode({n:2,c:{lat:[1]}}),/length/);
const locations=Geo.locationIndex([{id:'123',lat:-9.5,lon:-69.5}]);
const references=Audit.referenceIndex([{chave:'K1',alim:'F1',lat:-9.5,lon:-69.5,conj:'42'}],index);
const source=[{os:'OS1',lat:-9.4,lon:-69.4,conj:'OUTRO'},{os:'OS1',poste:'226-123'},{os:'OS2',chave:'K1'},{os:'OS3',lat:91,lon:-69}];
const records=Audit.classify(source,index,locations,references,'os_abertas');
assert.equal(records[0].row.conjCode,'42');assert.equal(records[0].row.conjConflict,true);
assert.equal(records[1].row.locationMethod,'Vínculo exato pelo poste');assert.equal(records[1].row.conjCode,'42');
assert.equal(records[2].row.conjStatus,'sem_coordenada');assert.equal(records[2].row.point,null);assert.equal(records[2].reference.status,'conjunto_unico_da_referencia');
assert.equal(records[3].row.conjStatus,'coordenada_invalida');
const summary=Audit.summarize(records,names);assert.equal(summary.classified,2);assert.equal(summary.unlocated,2);assert.equal(summary.conflicts,1);assert.equal(summary.referenceOnlyUnique,1);
const orders=Audit.orderStats(source);assert.equal(orders.uniqueOsIds,3);assert.equal(orders.additionalRowsForRepeatedOsIds,1);
assert.equal(Audit.orderStats([{dia:1},{dia:2}]).rowsWithoutOsId,2);
assert.equal(Audit.csvCell('=bad'),'"\'=bad"');assert.equal(Audit.csvCell(-9.5),'"-9.5"');
assert.equal(source[0].conj,'OUTRO');assert.equal(source[1].lat,undefined);
console.log('audit-conjuntos: columnar decoding, spatial/pole evidence, reference-only separation, conflicts, duplicate OS and CSV checks passed');
