'use strict';
const assert=require('node:assert/strict');
const {score,rank}=require('../docs/sigora-engine.js');
const base={id:'RBR-001',occurrences90:6,decMinutes90:60,customers:500,loadingPct:80,vegetationRisk:0.5};
const full=score(base);
assert.equal(full.status,'COMPLETE');assert.equal(full.coverage,1);
assert.equal(full.score,54.5);assert.equal(full.scoreUpper,54.5);
assert.equal(full.calibrated,false);
const incomplete=score({...base,vegetationRisk:null});
assert.equal(incomplete.status,'INCOMPLETE');
assert.equal(incomplete.coverage,0.85);
assert.equal(incomplete.score,47);assert.equal(incomplete.scoreUpper,62);
assert.ok(incomplete.missing.includes('vegetationRisk'));
const invalid=score({...base,customers:-3});
assert.equal(invalid.status,'INVALID');assert.equal(invalid.score,null);
assert.ok(invalid.invalid.includes('customers'));
assert.throws(()=>score({...base,id:''}),/Identificador/);
assert.throws(()=>score(base,{occurrences90:1,decMinutes90:1,customers:1,loadingPct:1,vegetationRisk:1}),/Pesos/);
assert.throws(()=>rank([base,{...base}]),/duplicado/);
assert.deepEqual(rank([{...base,id:'B',occurrences90:12},{...base,id:'A'}]).map(x=>x.id),['B','A']);
assert.equal(score({...base,decMinutes90:100000}).score,67);
console.log('PASS SIGORA: score, limites, dados ausentes, inválidos, pesos, duplicatas e ordenação.');
