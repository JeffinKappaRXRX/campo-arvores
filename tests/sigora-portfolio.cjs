'use strict';
const assert=require('node:assert/strict');
const {optimize}=require('../docs/sigora-portfolio.js');
const a={id:'A',budgetType:'CAPEX',cost:100,crewHours:3,riskReduction:5,decReduction:4,fecReduction:2,materials:{X:1}};
const b={...a,id:'B',budgetType:'OPEX',cost:70,crewHours:2,riskReduction:2,decReduction:3,fecReduction:3,materials:{X:2}};
const c={...a,id:'C',cost:80,crewHours:2,riskReduction:4,decReduction:3,fecReduction:1,exclusiveGroup:'G'};
const d={...a,id:'D',cost:90,crewHours:2,riskReduction:3,decReduction:3,fecReduction:1,exclusiveGroup:'G'};
const limits={CAPEX:100,OPEX:100,crewHours:5,materials:{X:3}};
let result=optimize([a,b],limits);
assert.deepEqual(result.frontier[0].ids,['A','B']);
assert.equal(result.frontier[0].riskReduction,7);
assert.equal(result.feasiblePortfolios,4);
result=optimize([a,b],{...limits,OPEX:0});
assert.ok(result.frontier.every(x=>!x.ids.includes('B')));
result=optimize([c,d],limits);
assert.ok(result.frontier.every(x=>x.ids.length<=1));
result=optimize([{...b,dependencies:['A']},a],limits);
assert.ok(result.frontier.every(x=>!x.ids.includes('B')||x.ids.includes('A')));
result=optimize([a],{...limits,materials:{X:0}});
assert.deepEqual(result.frontier[0].ids,[]);
assert.throws(()=>optimize([{...a,cost:null}],limits),/invalidos/);
assert.throws(()=>optimize([a,a],limits),/duplicado/);
assert.throws(()=>optimize([{...a,safetyBlocked:true}],limits),/bloqueado/);
assert.throws(()=>optimize([{...a,dependencies:['NAO_EXISTE']}],limits),/Dependencia/);
console.log('PASS SIGORA portfolio: limites CAPEX/OPEX, horas, materiais, exclusividade, dependencias e Pareto.');
