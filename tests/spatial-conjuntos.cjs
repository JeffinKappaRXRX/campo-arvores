const assert=require('node:assert/strict');
const C=require('../docs/ciclo-conjuntos.js');
const feature=(codigo,nome,rings)=>({type:'Feature',properties:{codigo,nome},geometry:{type:'Polygon',coordinates:rings}});
const shell=[[-70,-11],[-68,-11],[-68,-9],[-70,-9],[-70,-11]];
const hole=[[-69.6,-10.6],[-69.4,-10.6],[-69.4,-10.4],[-69.6,-10.4],[-69.6,-10.6]];
const second=[[-68,-11],[-66,-11],[-66,-9],[-68,-9],[-68,-11]];
const features=[feature('101','CONJUNTO A',[shell,hole]),feature('102','CONJUNTO B',[second])];
const source={sha256:'fixture',crs:'EPSG:31979'};
const index=C.spatial(features,'codigo',{},source);
assert.equal(index.classify([-10,-69]).code,'101');
assert.equal(index.classify([-10,-67]).code,'102');
assert.equal(index.classify([-10.5,-69.5]).status,'fora_cobertura','hole is excluded');
assert.equal(index.classify([-10.5,-69.4]).code,'101','hole edge is boundary of polygon');
assert.equal(index.classify([-11,-69]).code,'101','outer edge counts as covered');
assert.equal(index.classify([-10,-68]).status,'divisa_ambigua','shared edge does not pick a polygon arbitrarily');
assert.deepEqual(index.classify([-10,-68]).candidates.map(x=>x.code),['101','102']);
assert.equal(index.classify([NaN,-69]).status,'coordenada_invalida');
assert.equal(index.classify(null).status,'sem_coordenada');
const overlap=C.spatial([...features,feature('103','CONJUNTO C',[shell])],'codigo',{});
assert.equal(overlap.classify([-10,-69]).status,'divisa_ambigua','positive overlap stays ambiguous');
const conflict=C.classifyRow({id:'A',lat:-10,lon:-69,conj:'CONJUNTO B'},index);
assert.equal(conflict.conjCode,'101');assert.equal(conflict.conjOriginal,'CONJUNTO B');assert.equal(conflict.conjConflict,true);
assert.equal(conflict.conjSource.sha256,'fixture');
const locations=C.locationIndex([{id:'226-42',lat:-10,lon:-69},{id:'43',lat:-10,lon:-69},{id:'43',lat:-10,lon:-67}]);
const linked=C.classifyRow({id:'TREE',posteGIS:'42',lat:null,lon:null},index,locations);
assert.equal(linked.conjCode,'101');assert.equal(linked.locationMethod,'Vínculo exato pelo poste');
assert.equal(C.classifyRow({poste:'43'},index,locations).conjStatus,'poste_ambiguo');
assert.equal(C.classifyRow({chave:'C1',alim:'A1',conj:'CONJUNTO A'},index,locations).conjStatus,'sem_coordenada','feeder/key text is not spatial evidence');
assert.equal(C.pointOf({lat:'',lon:null}),null,'blank values are not zero coordinates');
assert.equal(C.classifyRow({lat:999,lon:-69},index).conjStatus,'coordenada_invalida');
assert.equal(C.classifyRow({lat:-8,lon:-69,poste:'42'},index,locations).conjStatus,'fora_cobertura','real point wins over linked pole');
assert.equal(C.pointInArea([-10,-69],[[-10.5,-69.5],[-10.5,-68.5],[-9.5,-68.5],[-9.5,-69.5]]),true);
assert.equal(C.audit([linked,conflict,C.classifyRow({},index)]).unlocated,1);
console.log('PASS spatial conjuntos: official codes, holes, edges, ambiguity, coordinate validation, exact pole links, conflict provenance and audit.');
