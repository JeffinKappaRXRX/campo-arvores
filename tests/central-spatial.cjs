const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),zlib=require('node:zlib');
const Geo=require('../docs/ciclo-conjuntos.js');
const table=rows=>({n:rows.length,c:Object.fromEntries([...new Set(rows.flatMap(Object.keys))].map(key=>[key,rows.map(row=>row[key])]))});
const feature=(code,west,east)=>({type:'Feature',properties:{codigo:code,nome:'Conjunto '+code},geometry:{type:'Polygon',coordinates:[[[west,-11],[east,-11],[east,-9],[west,-9],[west,-11]]]}});
const geo={type:'FeatureCollection',targetCRS:'EPSG:4326',source:{sha256:'test'},features:[feature('101',-70,-68),feature('102',-68,-66)]};
const responses=new Map();
const context=vm.createContext({console,document:{getElementById:()=>null},Date,Map,Set,Blob,Response,DecompressionStream,TextEncoder,URL,URLSearchParams,atob,CycleConjuntos:Geo,indexedDB:{},fetch:async path=>{const u=new URL(path,'https://test');return new Response(JSON.stringify({body:await responses.get(u.searchParams.get('generation')+':'+u.searchParams.get('name'))}));}});
const C=vm.runInContext(fs.readFileSync('docs/central-core.js','utf8')+';Central',context);
C.configureGeography(geo);
C.dados.parque_postes=table([{id:'42',lat:-10,lon:-69},{id:'43',lat:-10,lon:-67}]);
C.dados.os_abertas=table([{os:'A',poste:'42',conj:'102',chave:'C1'},{os:'B',poste:'43',chave:'C2'},{os:'MISSING',chave:'C3'}]);
C.dados.chaves=table([{chave:'C1'},{chave:'C2'},{chave:'C3'}]);
C.dados.cart_prog=table([{chave:'C1'},{chave:'C2'}]);
C.dados.poda_postes=table([{id:'42',lat:-10,lon:-69},{id:'43',lat:-10,lon:-67}]);
C.dados.vera_prev=table([{id:'TREE',lat:-10,lon:-69},{id:'TREE2',lat:-10,lon:-67}]);
assert.equal(C.linhas('os_abertas')[0].conj,'101');
assert.equal(C.linhasRaw('os_abertas')[0].conj,'102','raw source remains available');
const area=[[-10.5,-69.5],[-10.5,-68.5],[-9.5,-68.5],[-9.5,-69.5]];
C.setSpatialArea(area);
for(const name of ['os_abertas','poda_postes','vera_prev','parque_postes','chaves','cart_prog'])assert.equal(C.linhas(name).length,1,name+' follows same area');
assert.equal(C.spatialAudit('os_abertas').unlocated,1,'unlocated excluded from area but retained for audit');
C.setSpatialArea(null);assert.equal(C.linhas('os_abertas').length,3,'clear restores entire collection');
C.setSpatialArea([[NaN,0],[0,1],[1,0]]);assert.equal(C.getSpatialArea(),null,'invalid area rejected');
(async()=>{
 const zip=data=>zlib.gzipSync(JSON.stringify(data)).toString('base64');
 let resolveOld;responses.set('old:os_abertas',new Promise(resolve=>resolveOld=resolve));
 responses.set('new:os_abertas',zip(table([{os:'NEW',lat:-10,lon:-67}])));
 responses.set('new:conjuntos_geo',zip(geo));
 const old=C.carregar({generation:'old',manifest:{os_abertas:{parts:1}}},['os_abertas']);
 await C.carregar({generation:'new',manifest:{os_abertas:{parts:1},conjuntos_geo:{parts:1}}},['os_abertas']);
 resolveOld(zip(table([{os:'OLD'}])));await old;
 assert.equal(C.linhas('os_abertas')[0].os,'NEW','late old-generation response discarded');
 assert.equal(C.linhas('os_abertas')[0].conj,'102','new generation polygons autoload');
 console.log('PASS central spatial: shared area across OS, trees, poda, structures and portfolio; audited missing points; clear restores records; late generation discarded.');
})().catch(error=>{console.error(error);process.exitCode=1;});
